// Bouton « Force » : calculé à partir du taux d'alcool.
export const FORCES = [
  { id: 'legere', max: 4.6 },
  { id: 'moyenne', max: 6.5 },
  { id: 'forte', max: 101 }
];
export function forceDe(alcool) {
  if (alcool == null || alcool === '' || isNaN(alcool)) return null;
  return FORCES.find((f) => Number(alcool) < f.max).id;
}

